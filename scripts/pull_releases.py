#!/usr/bin/env python3
"""Bake the app's GitHub releases into src/lib/releases/data.ts.

The single-file site ships its release data inside the bundle; the page then
re-checks the API at runtime and swaps in anything newer. Regenerate with:

  python3 scripts/pull_releases.py            # codewiththiha/mareader2
  python3 scripts/pull_releases.py --repo owner/name

Standard library only, no token needed for a public repository.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "lib" / "releases" / "data.ts"
REPO_DEFAULT = "codewiththiha/mareader2"
HEADER = "// generated by scripts/pull_releases.py — do not edit by hand\n"


def fetch(repo: str) -> list[dict]:
    url = f"https://api.github.com/repos/{repo}/releases?per_page=30"
    req = urllib.request.Request(url, headers={
        "User-Agent": "mareader-site-releases",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    })
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.load(resp)


def shape(releases: list[dict]) -> list[dict]:
    out = []
    for r in releases:
        if r.get("draft"):
            continue
        out.append({
            "tag": r["tag_name"],
            "date": (r.get("published_at") or "")[:10],
            "body": r.get("body") or "",
            "assets": [{
                "name": a["name"],
                "size": a["size"],
                "url": a["browser_download_url"],
            } for a in sorted(r.get("assets", []), key=lambda a: a["name"])],
        })
    return out


def emit(releases: list[dict]) -> str:
    body = json.dumps(releases, indent=2, ensure_ascii=False)
    body = body.replace("\n", "\n")
    return (HEADER
            + "export interface ReleaseAsset {\n"
            + "  name: string;\n  size: number;\n  url: string;\n}\n\n"
            + "export interface Release {\n"
            + "  tag: string;\n  date: string;\n  body: string;\n"
            + "  assets: ReleaseAsset[];\n}\n\n"
            + f"export const RELEASES: Release[] = {body};\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", default=REPO_DEFAULT)
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    releases = shape(fetch(args.repo))
    if not releases:
        print(f"{args.repo}: no published releases found", file=sys.stderr)
        return 1
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(emit(releases), encoding="utf-8")
    total = sum(len(r["assets"]) for r in releases)
    print(f"wrote {out.relative_to(ROOT)}: {len(releases)} releases, {total} assets "
          f"(latest {releases[0]['tag']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
