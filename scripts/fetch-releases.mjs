// Snapshot GitHub release notes into src/lib/site/releases.ts for offline use.
import { writeFile } from "node:fs/promises";

const REPO = "codewiththiha/mareader2";
const COUNT = 5;

const res = await fetch(`https://api.github.com/repos/${REPO}/releases?per_page=${COUNT}`);
if (!res.ok) throw new Error(`releases api: ${res.status}`);
const list = await res.json();
const pick = (r) => ({
  tag: r.tag_name,
  name: r.name || r.tag_name,
  published: (r.published_at || "").slice(0, 10),
  body: String(r.body || "").trim(),
  assets: (r.assets || []).map((a) => ({ name: a.name, size: a.size, url: a.browser_download_url })),
});
const ts = `// Generated by scripts/fetch-releases.mjs; rerun after a release, do not edit.
import type { Release } from "./releases-type";

export const RELEASES: Release[] = ${JSON.stringify(list.map(pick), null, 2)};
`;
await writeFile(new URL("../src/lib/site/releases.ts", import.meta.url), ts);
console.log(`releases.ts: ${list.length} releases, latest ${list[0]?.tag_name}`);
